import os
from typing import Dict, Any, List, Optional
from langchain_core.documents import Document
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.runnables import RunnablePassthrough
from langchain_core.output_parsers import StrOutputParser
from langchain_google_genai import ChatGoogleGenerativeAI
from langchain_chroma import Chroma
from src import config

def format_docs(docs: List[Document]) -> str:
    """Helper to concatenate retrieved document contents with clear separation."""
    return "\n---\n".join(doc.page_content for doc in docs)

def get_llm(model_name: Optional[str] = None, api_key: Optional[str] = None) -> ChatGoogleGenerativeAI:
    """Initializes ChatGoogleGenerativeAI LLM instance."""
    key = api_key or config.GEMINI_API_KEY or os.getenv("GOOGLE_API_KEY")
    if not key:
        raise ValueError("Google Gemini API Key is missing. Please set GOOGLE_API_KEY in .env.")

    m_name = model_name or config.LLM_MODEL
    return ChatGoogleGenerativeAI(
        model=m_name,
        google_api_key=key,
        temperature=0.0
    )

def create_rag_chain(
    vectorstore: Chroma,
    k: Optional[int] = None,
    prompt_template: Optional[str] = None,
    model_name: Optional[str] = None,
    api_key: Optional[str] = None
):
    """
    Builds the LCEL RAG chain (matching Step 7 & 8 of reference notebook).
    Returns (rag_chain, retriever).
    """
    retriever_k = k or config.RETRIEVER_K
    retriever = vectorstore.as_retriever(search_kwargs={"k": retriever_k})

    template_str = prompt_template or config.DEFAULT_PROMPT_TEMPLATE
    prompt = ChatPromptTemplate.from_template(template_str)

    llm = get_llm(model_name=model_name, api_key=api_key)

    rag_chain = (
        {"context": retriever | format_docs, "question": RunnablePassthrough()}
        | prompt
        | llm
        | StrOutputParser()
    )

    return rag_chain, retriever

def query_rag_pipeline(rag_chain, retriever, query: str) -> Dict[str, Any]:
    """
    Executes a query through the RAG pipeline.
    Returns a dictionary containing:
      - 'query': original question
      - 'retrieved_docs': list of retrieved Document objects
      - 'answer': string answer generated by the LLM
    """
    print(f"\n[RAG Pipeline] Processing Query: \"{query}\"")

    # 1. Retrieve matching chunks
    retrieved_docs = retriever.invoke(query)

    # 2. Generate answer through LCEL chain
    answer = rag_chain.invoke(query)

    return {
        "query": query,
        "retrieved_docs": retrieved_docs,
        "answer": answer.strip()
    }

